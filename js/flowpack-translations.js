// Generic data-translate attribute handler
function applyFlowpackTranslations() {
    const currentLang = localStorage.getItem('girisim_lang') || 'tr';
    const trans = flowpackTranslations[currentLang] || flowpackTranslations.tr;

    document.querySelectorAll('[data-translate]').forEach(el => {
        const key = el.getAttribute('data-translate');
        const value = getNestedValue(trans, key);
        if (value) {
            el.innerHTML = value;
        }
    });

    // Handle RTL for Arabic
    if (currentLang === 'ar') {
        document.documentElement.setAttribute('dir', 'rtl');
        document.body.classList.add('rtl');
    } else {
        document.documentElement.setAttribute('dir', 'ltr');
        document.body.classList.remove('rtl');
    }
}

// Helper function to get nested object values
function getNestedValue(obj, path) {
    return path.split('.').reduce((current, key) => current && current[key], obj);
}

// Initialize on page load
if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', applyFlowpackTranslations);
} else {
    applyFlowpackTranslations();
}

// Re-apply when language changes
window.addEventListener('storage', function(e) {
    if (e.key === 'girisim_lang') {
        applyFlowpackTranslations();
    }
});

// Export for manual triggering
window.applyFlowpackTranslations = applyFlowpackTranslations;
